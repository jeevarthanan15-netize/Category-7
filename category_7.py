colors = ['Red', 'Green', 'Blue']
neighbors = {
    'A': ['B', 'C'],
    'B': ['A', 'C', 'D'],
    'C': ['A', 'B', 'D'],
    'D': ['B', 'C']
}
assignment = {}
def is_valid(region, color):
    for neighbor in neighbors[region]:
        if neighbor in assignment and assignment[neighbor] == color:
            return False
    return True
def map_coloring():
    if len(assignment) == len(neighbors):
        return True
    for region in neighbors:
        if region not in assignment:
            break
    for color in colors:
        if is_valid(region, color):
            assignment[region] = color
            if map_coloring():
                return True
            del assignment[region]
    return False
if map_coloring():
    print("Map Coloring Solution:")
    for region, color in assignment.items():
        print(region, "->", color)
else:
    print("No solution")

"""Crypt-Arithmetic Puzzle"""

from itertools import permutations
letters = ['S', 'E', 'N', 'D', 'M', 'O', 'R', 'Y']
def solve_cryptarithm():
    for digits in permutations(range(10), 8):
        values = dict(zip(letters, digits))
        if values['S'] == 0 or values['M'] == 0:
            continue
        SEND = (
            values['S'] * 1000 +
            values['E'] * 100 +
            values['N'] * 10 +
            values['D']
        )
        MORE = (
            values['M'] * 1000 +
            values['O'] * 100 +
            values['R'] * 10 +
            values['E']
        )
        MONEY = (
            values['M'] * 10000 +
            values['O'] * 1000 +
            values['N'] * 100 +
            values['E'] * 10 +
            values['Y']
        )
        if SEND + MORE == MONEY:
            return values, SEND, MORE, MONEY
    return None
result = solve_cryptarithm()
if result:
    values, SEND, MORE, MONEY = result
    print("Solution:")
    for letter, digit in values.items():
        print(letter, "=", digit)
    print()
    print(SEND)
    print("+", MORE)
    print("=", MONEY)
else:
    print("No solution")

"""Local Search for CSP"""

import random
N = 8
def conflicts(board):
    total = 0
    for i in range(N):
        for j in range(i + 1, N):
            if board[i] == board[j]:
                total += 1
            if abs(board[i] - board[j]) == abs(i - j):
                total += 1
    return total
def get_neighbors(board):
    neighbors = []
    for row in range(N):
        for col in range(N):
            if col != board[row]:
                new_board = board[:]
                new_board[row] = col
                neighbors.append(new_board)
    return neighbors
def hill_climbing():
    board = [random.randint(0, N - 1) for _ in range(N)]
    while True:
        current_conflicts = conflicts(board)
        if current_conflicts == 0:
            return board
        neighbors = get_neighbors(board)
        best_board = min(neighbors, key=conflicts)
        best_conflicts = conflicts(best_board)
        if best_conflicts >= current_conflicts:
            board = [random.randint(0, N - 1) for _ in range(N)]
        else:
            board = best_board
solution = hill_climbing()
print("8-Queens Solution:")
print(solution)
print("Conflicts:", conflicts(solution))